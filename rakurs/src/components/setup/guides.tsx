/* ── Воронка ───────────────────────────────────────────────────────────── */

export function FunnelGuide() {
  return (
    <Steps>
      <Step n={1} title="Посмотрите на стадии, с которыми агент уже создан">
        <div>
          Их девять — от «Новый лид» до «Продажи» и «Отказа». Это не образец для подражания,
          а болванка, чтобы доска не была пустой в первый день. Открывается в{' '}
          <Inside to="../settings">«Настройках»</Inside>, карточка «Воронка».
        </div>
      </Step>
      <Step n={2} title="Переименуйте стадии под свою продажу и удалите лишние">
        <div>
          Стадия — это ответ на «что с лидом происходит сейчас». Если у вас нет счетов,
          стадия «Счёт отправлен» будет пустой всегда и только мешать читать статистику.
        </div>
        <Note kind="warn">
          У каждой стадии есть тип: обычная, квалифицирующая, ожидание оплаты, продажа, отказ.
          Тип «Продажа» должен быть ровно у одной стадии — именно её достижение считают
          статистика и отправка покупок в Meta.
        </Note>
      </Step>
      <Step n={3} title="Опишите стадии словами — их читает ИИ-агент">
        <div>
          Поле «Когда лид попадает в эту стадию» — это инструкция агенту, по которой он двигает
          карточки. Пустое описание означает, что двигать он её не будет.
        </div>
      </Step>
      <Step n={4} title="Настройте автосообщение там, где оно уместно">
        <div>
          Сообщение уходит клиенту при входе в стадию; <Path>{'{{name}}'}</Path> подставит его
          имя. Работает и когда карточку двигает человек, и когда агент.
        </div>
      </Step>
      <Step n={5} title="Соберите поля лида — то, что нужно узнать у каждого клиента">
        <div>
          Карточка «Поля лида» в тех же настройках. Имя, город, бюджет, адрес доставки —
          то, что потом попадёт в выгрузку клиентов и в подсказки агенту.
        </div>
        <Note>
          Переименование поля сохраняет ответы, удаление — уносит их вместе с полем. Это
          единственное необратимое действие в этой карточке.
        </Note>
      </Step>
      <Step n={6} title="Проверьте на живом лиде">
        <div>
          Откройте <Inside to="../funnel">«Воронка»</Inside>, перетащите карточку между стадиями
          и заполните пару полей в панели лида. Подтверждённые оплаты появляются в разделе «Заказы».
        </div>
      </Step>
    </Steps>
  );
}

/* ── База знаний ───────────────────────────────────────────────────────── */

export function KnowledgeGuide() {
  return (
    <Steps>
      <Step n={1} title="Начните с вопросов, которые клиенты задают каждый день">
        <div>
          Доставка, цены, сроки, возврат, гарантия, адрес. Заметок должно быть достаточно,
          чтобы агенту было что процитировать: пустая база превращает его в переадресацию на
          человека.
        </div>
      </Step>
      <Step n={2} title="Заводите заметки по одной: «+ Новая заметка»">
        <div>
          Раздел <Inside to="../knowledge">«База знаний»</Inside>. База устроена как хранилище
          заметок в папках, как в Obsidian: у заметки есть путь вроде{' '}
          <Path>Товары/Двери входные</Path>, а папка — просто часть этого пути. Разбивайте
          текст заголовками markdown (<Path>##</Path>) — агент цитирует клиенту не всю заметку,
          а ровно тот раздел под заголовком, который отвечает на вопрос.
        </div>
      </Step>
      <Step n={3} title="Или занесите текст пачкой — карточка «Загрузить»">
        <div>
          «Вставить текст»: прайс или список вопрос-ответ режется на отдельные заметки по
          пустой строке между блоками, и каждая ложится в папку «Вставки». «Загрузить
          страницу» читает вашу страницу сайта по адресу и заводит из неё ровно одну заметку —
          её заголовки на странице становятся заголовками markdown внутри.
        </div>
      </Step>
      <Step n={4} title="Проверьте поиском — тем же, которым пользуется агент">
        <div>
          Поле «Вопрос клиента» сверху ищет ровно так же, как ищет агент перед ответом. Если по
          вопросу клиента ничего не находится — агент тоже ничего не найдёт и передаст диалог
          человеку.
        </div>
      </Step>
      <Step n={5} title="Держите базу живой">
        <div>
          У источника-страницы в карточке «Загрузить» есть кнопка «Обновить» — она читает страницу
          заново. Заметку, которую вы хоть раз поправили руками, обновление не тронет: рядом
          появится свежая копия с сайта, а ваша правка останется как была. Устаревшая заметка
          хуже отсутствующей: агент процитирует её уверенно.
        </div>
      </Step>
    </Steps>
  );
}

/* ── ИИ-агент ──────────────────────────────────────────────────────────── */

export function AgentGuide() {
  return (
    <Steps>
      <Step n={1} title="Сохраните ключ OpenRouter">
        <div>
          Ключ берётся на <Out href={OPENROUTER_KEYS_URL}>openrouter.ai/keys</Out> и вставляется
          в <Inside to="../agent">разделе «Агент»</Inside>, карточка «Ключ OpenRouter». Ответы
          моделей оплачиваются с вашего счёта в OpenRouter — кабинет за них не платит.
        </div>
      </Step>
      <Step n={2} title="Опишите характер агента в «Обучении»">
        <div>
          Характер агента — не одно поле, а список правил в четырёх категориях: о компании, как
          говорить, о чём спрашивать, чего не делать. Пишете их сами кнопкой «+ Добавить
          правило» в разделе <Inside to="../coach">«Обучение»</Inside>, или диктуете обычным
          текстом в чате рядом — коуч предложит формулировку, а заносит её всё равно владелец.
          Пишите конкретно — «не называй сроки доставки в другие города, передай менеджеру»
          работает, «будь вежливым» не значит ничего.
        </div>
      </Step>
      <Step n={3} title="Выберите модель и язык ответа">
        <div>
          Список моделей — в карточке «Модель», рядом с каждой написано, чем она отличается.
          Язык «авто» отвечает на языке клиента.
        </div>
      </Step>
      <Step n={4} title="Прогоните агента в песочнице">
        <div>
          Карточка «Проверить агента»: вы пишете фразу клиента и видите, что агент ответил бы,
          какие разделы базы знаний он для этого взял и куда двинул бы лид. Клиенту ничего не
          уходит, в переписке ничего не остаётся.
        </div>
        <Note kind="warn">
          Единственный честный способ проверить правила — задать неудобный вопрос: скидка,
          срок, обещание, которого вы не даёте. Если агент его выдумал — правьте правила в
          «Обучении», а не модель.
        </Note>
      </Step>
      <Step n={5} title="Включите агента">
        <div>
          Тумблер «Агент отвечает клиентам» в том же разделе. До этого момента отвечают только
          люди, что бы ни было настроено.
        </div>
      </Step>
      <Step n={6} title="Знайте, где его выключить в отдельном диалоге">
        <div>
          В любой переписке есть переключатель агента: если он повёл разговор не туда,
          оператор забирает диалог себе, не выключая агента у остальных.
        </div>
      </Step>
      <Step n={7} title="Следите за расходом">
        <div>
          Карточка «Расход» показывает, во что обошлись ответы за сутки, неделю и месяц, и
          сколько потратила каждая модель. Точный счёт — в аккаунте OpenRouter.
        </div>
      </Step>
    </Steps>
  );
}

/* ── Meta Conversions API ──────────────────────────────────────────────── */

export function CapiGuide() {
  return (
    <Steps>
      <Step n={1} title="Решите, нужен ли вам этот этап">
        <div>
          Он нужен, только если вы ведёте рекламу Click-to-WhatsApp. Отчёты уходят
          исключительно по диалогам, начавшимся с клика по объявлению: диалог, в котором клиент
          написал сам, Meta не с чем сопоставить.
        </div>
      </Step>
      <Step n={2} title="Возьмите идентификатор набора данных">
        <div>
          <Out href={EVENTS_MANAGER_URL}>Meta Events Manager</Out> →{' '}
          <Path>Data sources</Path> → ваш набор данных → <Path>Settings</Path>. Это тот же
          набор (пиксель), который используют ваши объявления, — чужой примет события и не
          свяжет их с рекламой.
        </div>
      </Step>
      <Step n={3} title="Выпустите токен с правом на этот набор">
        <div>
          Постоянный токен системного пользователя, которому в{' '}
          <Path>Business settings → Assign assets</Path> выдан доступ к этому набору данных.
          Порядок тот же, что и для WhatsApp на этапе выше.
        </div>
      </Step>
      <Step n={4} title="Сохраните пару в «Интеграциях»">
        <div>
          Карточка «Отправка покупок в Meta». Кабинет проверяет пару в Meta до записи: набор с
          опечаткой примут молча все, кроме Meta, — поэтому отказ показывается целиком и
          ничего не перезаписывает.
        </div>
      </Step>
      <Step n={5} title="Проверьте тестовым кодом события">
        <div>
          Поле «Тестовый код события» берётся в Events Manager, вкладка <Path>Test Events</Path>.
          Пока код указан, события видны там и не идут в оптимизацию рекламы.
        </div>
        <Note kind="warn">
          Уберите код, когда убедились, что события доходят. С ним отправка работает вхолостую:
          реклама этих покупок не увидит.
        </Note>
      </Step>
      <Step n={6} title="Включите отправку и следите за журналом">
        <div>
          Продажа уходит примерно за минуту после отметки об оплате. Журнал «Что ушло в Meta»
          показывает каждое событие и причину отказа; строку можно отправить заново — Meta
          считает одну конверсию на событие, сколько бы раз его ни повторили.
        </div>
      </Step>
    </Steps>
  );
}

