/**
 * Два решения карточки «Движение по воронке», вынесенные из разметки.
 *
 * Оба — про то, чтобы напечатанное было правдой, а не про то, как оно выглядит: как
 * показать долю, которая округляется в ноль, и что написать, когда цепочка пуста, а
 * переходы за период были. Здесь они чистые функции, потому что проверять их надо
 * поштучно, а не глазами по экрану.
 */
import type { FunnelStep, StatsPeriodReport } from '@/types';

/**
 * Написано escape-последовательностью, а не символом, по причине из `lib/money.ts`:
 * неразрывный пробел в исходнике неотличим от обычного, и один невнимательный прогон
 * форматтера превращает «12 %» в строку, которая может разорваться между числом и знаком.
 */
const NO_BREAK_SPACE = '\u00a0';

/**
 * Доля целыми процентами — кроме той, что меньше одного.
 *
 * Числами, а не строками, и это не оговорка: конверсия — отношение двух счётчиков, а не
 * деньги. Округлять её до целого можно, а сумму — нельзя.
 *
 * Один лид из двухсот пятидесяти — это 0,4 %, и `Math.round` печатал под ним «0 %». Ровно
 * это карточка приберегла для «доли нет вовсе»: ноль в ней — обвинение, а не число. Поэтому
 * всё, что меньше процента, показывается как «<1 %» — доля есть, она просто мала.
 */
export function percent(share: number): string {
  const whole = Math.round(share * 100);
  if (whole === 0) return `<1${NO_BREAK_SPACE}%`;
  return `${whole}${NO_BREAK_SPACE}%`;
}

/**
 * Почему в цепочке нечего рисовать — и есть ли вообще такая причина.
 *
 * - `null` — цепочку рисуем, в какие-то стадии за период заходили.
 * - `'nothing-moved'` — за период не двигали никого и никуда.
 * - `'off-chain'` — двигали, но только туда, чего в цепочке нет: в стадию-отказ или в
 *   стадию, которую с тех пор удалили.
 *
 * Третий случай — та самая причина, по которой это отдельная функция, а не `every()` в
 * разметке. Пустая цепочка и фраза «лидов по воронке не двигали» под ней соседствовали с
 * плиткой «Отказов: 12» — то есть с двенадцатью переходами, о которых только что сказали,
 * что их не было.
 */
export type ChainAbsence = 'nothing-moved' | 'off-chain' | null;

export function chainAbsence(
  report: Pick<StatsPeriodReport, 'failureEntries' | 'deletedStageEntries'> & {
    funnel: Pick<FunnelStep, 'entered'>[];
  },
): ChainAbsence {
  if (report.funnel.some((step) => step.entered > 0)) return null;
  return report.failureEntries > 0 || report.deletedStageEntries > 0
    ? 'off-chain'
    : 'nothing-moved';
}
